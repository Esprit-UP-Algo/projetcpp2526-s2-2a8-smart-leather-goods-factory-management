DROP TABLE REF_ARTICLES_MARCHE CASCADE CONSTRAINTS;
DROP SEQUENCE seq_ref_articles;

CREATE TABLE REF_ARTICLES_MARCHE (
    id_article         NUMBER PRIMARY KEY,
    reference          VARCHAR2(50) UNIQUE NOT NULL,
    nom                VARCHAR2(100),
    categorie          VARCHAR2(100),
    type               VARCHAR2(50),
    couleur            VARCHAR2(50),
    dimension          VARCHAR2(50),
    prix_unitaire      NUMBER(10,2),
    cout_fabrication   NUMBER(10,2),
    statut             VARCHAR2(50),
    date_creation      DATE
);

CREATE SEQUENCE seq_ref_articles START WITH 1 INCREMENT BY 1;

CREATE OR REPLACE TRIGGER trg_ref_articles_id
BEFORE INSERT ON REF_ARTICLES_MARCHE
FOR EACH ROW
BEGIN
    IF :NEW.ID_ARTICLE IS NULL THEN
        SELECT seq_ref_articles.NEXTVAL INTO :NEW.ID_ARTICLE FROM DUAL;
    END IF;
END;
