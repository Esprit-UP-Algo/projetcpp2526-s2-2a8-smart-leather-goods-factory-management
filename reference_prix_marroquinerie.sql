-- ================================================================
-- VÉRIFICATION
-- ================================================================
SELECT CATEGORIE,
       COUNT(*)                                    AS NB_ARTICLES,
       ROUND(AVG(PRIX_UNITAIRE), 2)                AS PRIX_MOY,
       ROUND(AVG(COUT_FABRICATION), 2)             AS COUT_MOY,
       ROUND(AVG(PRIX_UNITAIRE/COUT_FABRICATION),2) AS RATIO_MOY
FROM REF_ARTICLES_MARCHE
GROUP BY CATEGORIE
ORDER BY CATEGORIE;
